#!/usr/bin/env node
// Builds single-file artifacts (no bundler, no dependencies):
//   dist/h2f-core.js         core library (grid, extract, layout, components, tokens, pipeline, ai + samples)
//   plugin/dist/code.js      Figma main thread
//   plugin/dist/ui.html      Figma UI with the core inlined
//   web/dist/index.html      website with the core inlined
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const r = (p) => readFileSync(join(root, p), 'utf8');
const w = (p, s) => {
  mkdirSync(dirname(join(root, p)), { recursive: true });
  writeFileSync(join(root, p), s);
  console.log('  wrote', p, `(${(s.length / 1024).toFixed(1)} KB)`);
};

const CORE = ['grid', 'extract', 'layout', 'components', 'tokens', 'pipeline', 'ai'];

const samples = {
  pricing: { label: 'Pricing page (desktop)', screen: 'desktop', html: r('samples/pricing.html') },
  login: { label: 'Sign-in screen (mobile)', screen: 'iphone-16', html: r('samples/mobile-login.html') },
  dashboard: { label: 'Dashboard list (laptop)', screen: 'laptop', html: r('samples/dashboard.html') },
};

const core =
  `/* html-to-figma core — generated by scripts/build.mjs, do not edit */\n` +
  CORE.map((f) => r(`core/${f}.js`)).join('\n') +
  `\n(function(root){ (root.H2F = root.H2F || {}).SAMPLES = ${JSON.stringify(samples)}; })(typeof globalThis !== 'undefined' ? globalThis : this);\n`;

// keep inline <script> safe
const inlineSafe = (js) => js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

w('dist/h2f-core.js', core);
w('plugin/dist/code.js', r('plugin/src/code.js'));
w('plugin/dist/ui.html', r('plugin/src/ui.html').replace('/*__H2F_CORE__*/', () => inlineSafe(core)));
w('web/dist/index.html', r('web/src/index.html').replace('/*__H2F_CORE__*/', () => inlineSafe(core)));
// downloadable sample files for the website
mkdirSync(join(root, 'web/dist/samples'), { recursive: true });
for (const f of readdirSync(join(root, 'samples'))) copyFileSync(join(root, 'samples', f), join(root, 'web/dist/samples', f));
console.log('done');
